import { readFile, writeFile } from "node:fs/promises";
import { registerHooks } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

// Production TypeScript uses NodeNext `.js` specifiers. The generator runs the
// source contract directly on Node 24, so resolve those local specifiers to the
// corresponding `.ts` source without introducing a second metadata file.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (
      specifier.startsWith(".") &&
      specifier.endsWith(".js") &&
      context.parentURL?.includes("/src/") === true
    ) {
      return nextResolve(`${specifier.slice(0, -3)}.ts`, context);
    }
    return nextResolve(specifier, context);
  },
});

const { ACTION_INPUT_CONTRACT, ACTION_INPUT_DOC_GROUPS } =
  await import("../src/action-contract.ts");

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const write = process.argv.slice(2).includes("--write");

function quotedYaml(value) {
  return JSON.stringify(value);
}

function actionInputsBlock() {
  return ACTION_INPUT_CONTRACT.map((input) =>
    [
      `  ${input.name}:`,
      `    description: ${quotedYaml(input.description)}`,
      `    required: ${String(input.required)}`,
      ...(input.default === undefined ? [] : [`    default: ${quotedYaml(input.default)}`]),
    ].join("\n"),
  ).join("\n");
}

function markdownCell(value, escapeMarkdown = true) {
  const cell = value.replaceAll("|", "\\|").replaceAll("\n", " ");
  return escapeMarkdown ? cell.replaceAll("*", "\\*") : cell;
}

function requiredOrDefault(input) {
  if (input.required) return "Required";
  if (input.default === "") return "Empty";
  if (input.default === undefined) return "Optional";
  return `\`${input.default}\``;
}

function documentationTable(group) {
  const inputs = ACTION_INPUT_CONTRACT.filter((input) => input.docsGroup === group);
  const rows = inputs.map(
    (input) =>
      `| \`${input.name}\` | ${markdownCell(requiredOrDefault(input), false)} | ${markdownCell(input.description)} |`,
  );
  return ["| Input | Required/default | Description |", "| --- | --- | --- |", ...rows].join("\n");
}

function replaceBlock(source, start, end, contents, path) {
  const startIndex = source.indexOf(start);
  const endIndex = source.indexOf(end);
  if (startIndex < 0 || endIndex < 0 || endIndex < startIndex) {
    throw new Error(`${path} is missing generated markers ${start} / ${end}`);
  }
  const contentStart = startIndex + start.length;
  return `${source.slice(0, contentStart)}\n${contents}\n${source.slice(endIndex)}`;
}

async function formatted(contents, path) {
  const filepath = resolve(root, path);
  return prettier.format(contents, { ...(await prettier.resolveConfig(filepath)), filepath });
}

async function expectedAction() {
  const path = "action.yml";
  const source = await readFile(resolve(root, path), "utf8");
  return formatted(
    replaceBlock(
      source,
      "  # BEGIN GENERATED ACTION INPUTS",
      "  # END GENERATED ACTION INPUTS",
      actionInputsBlock(),
      path,
    ),
    path,
  );
}

async function expectedDocumentation() {
  const path = "docs/configuration.md";
  let source = await readFile(resolve(root, path), "utf8");
  for (const group of ACTION_INPUT_DOC_GROUPS) {
    source = replaceBlock(
      source,
      `<!-- BEGIN GENERATED ACTION INPUTS: ${group.id} -->`,
      `<!-- END GENERATED ACTION INPUTS: ${group.id} -->`,
      documentationTable(group.id),
      path,
    );
  }
  return formatted(source, path);
}

async function expectedInstallerMetadata() {
  const path = "packages/create-deepseek-harness-action/src/action-inputs.generated.mjs";
  const installerInputs = ACTION_INPUT_CONTRACT.filter((input) => input.installer === true);
  const entries = installerInputs.map((input) => {
    if (input.default === undefined) {
      throw new Error(`Installer input ${input.name} must declare a default`);
    }
    return `  ${input.runtimeKey}: Object.freeze(${JSON.stringify(
      { name: input.name, defaultValue: input.default },
      undefined,
      2,
    )}),`;
  });
  return {
    path,
    contents: await formatted(
      [
        "// Generated by scripts/generate-action-contract.mjs. Do not edit.",
        "export const INSTALLER_ACTION_INPUTS = Object.freeze({",
        ...entries,
        "});",
        "",
      ].join("\n"),
      path,
    ),
  };
}

const installer = await expectedInstallerMetadata();
const targets = [
  { path: "action.yml", contents: await expectedAction() },
  { path: "docs/configuration.md", contents: await expectedDocumentation() },
  installer,
];
const drift = [];
for (const target of targets) {
  let current;
  try {
    current = await readFile(resolve(root, target.path), "utf8");
  } catch (error) {
    if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) throw error;
    current = undefined;
  }
  if (current === target.contents) continue;
  drift.push(target.path);
  if (write) await writeFile(resolve(root, target.path), target.contents, "utf8");
}

if (drift.length > 0 && !write) {
  throw new Error(
    `Generated Action contract artifacts drifted: ${drift.join(", ")}. Run npm run generate:action-contract.`,
  );
}
if (write) {
  process.stdout.write(
    drift.length === 0
      ? "Action contract artifacts already up to date.\n"
      : `Updated Action contract artifacts: ${drift.join(", ")}\n`,
  );
}
